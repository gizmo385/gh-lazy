//! The generated `/pulls` and `/search/issues` parity fixtures (#384).
//!
//! The PR table lists `GET /repos/{o}/{r}/pulls` (`pull_requests.owner_filter = all`) or searches
//! `GET /search/issues` (`mine`), where Python takes the PRs out of the issues endpoint's pages (Py bug B180). So that
//! both apps' PR tables show the same rows in the parity scenarios, every issues-endpoint list page in a fixture set
//! gets a mirror: the same page of the same filters, holding the page's items that have `draft`, verbatim and in
//! order. `cargo xtask pr-list-fixtures` writes them next to their sources, and a test checks the committed files
//! match.
//!
//! Pages are mirrored one to one, so a page with no PRs gives an empty `/pulls` page. The sets listed in
//! [`HAND_WRITTEN`] write their own instead.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use fake_gh::fixture::{
    Fixture, FixtureRequest, Query, RequestKey, Response, dir_for, numbered_file_name, query_from_pairs,
};
use serde_json::{Value, json};

/// Where the fixture sets live, from the repo root.
pub const FIXTURES_DIR: &str = "parity/fixtures";

/// Sets whose `/pulls` and search pages are written by hand: `pr-list-issues-first`'s pages are the repo's PRs
/// regrouped, not its issues pages mirrored.
pub const HAND_WRITTEN: &[&str] = &["pr-list-issues-first"];

/// How each generated fixture's `note` starts, which is also how [`write`] finds the files it wrote before.
const NOTE_PREFIX: &str = "generated by cargo xtask pr-list-fixtures from ";

/// A source the generator can't read or mirror.
#[derive(Debug, thiserror::Error)]
pub enum Error {
    #[error("{}: {source}", path.display())]
    Io { path: PathBuf, source: std::io::Error },
    #[error("{}: {source}", path.display())]
    Parse { path: PathBuf, source: serde_json::Error },
    #[error("{}: {message}", path.display())]
    Unsupported { path: PathBuf, message: String },
}

/// One issues-endpoint list fixture, as read.
struct Source {
    set: String,
    /// Relative to [`FIXTURES_DIR`], with `/` separators, for the note.
    rel: String,
    /// The `.<n>` its file name carries (1 for none), kept on its mirror.
    number: u32,
    owner: String,
    repo: String,
    fixture: Fixture,
}

impl Source {
    fn query_value(&self, key: &str) -> Option<&str> {
        self.fixture
            .request
            .query
            .get(key)
            .and_then(|value| value.values().first())
            .map(String::as_str)
    }

    /// The page's pull requests, if it answered with a list.
    fn pull_requests(&self) -> Option<Vec<Value>> {
        let response = &self.fixture.response;
        if !(200..300).contains(&response.status) {
            return None;
        }
        let items = response.body.as_ref()?.as_array()?;
        Some(
            items
                .iter()
                .filter(|item| item.get("draft").is_some())
                .cloned()
                .collect(),
        )
    }
}

/// The `q` the app searches for `owner/repo`'s pull requests by the logged-in user in `state`: the rule of
/// `lazy_github_core::github::search::pull_request_search_q`.
pub fn pull_request_search_q(owner: &str, repo: &str, state: &str) -> String {
    let mut q = format!("is:pr repo:{owner}/{repo} author:@me");
    match state {
        "open" => q.push_str(" is:open"),
        "closed" => q.push_str(" is:closed"),
        _ => {}
    }
    q
}

/// Whether `name` is a `.json` file's.
fn is_json(name: &str) -> bool {
    Path::new(name)
        .extension()
        .is_some_and(|extension| extension.eq_ignore_ascii_case("json"))
}

/// Every file under `dir`, sorted.
fn walk(dir: &Path) -> Result<Vec<PathBuf>, Error> {
    let mut files = Vec::new();
    let mut stack = vec![dir.to_path_buf()];
    while let Some(dir) = stack.pop() {
        let entries = std::fs::read_dir(&dir).map_err(|source| Error::Io {
            path: dir.clone(),
            source,
        })?;
        for entry in entries {
            let path = entry
                .map_err(|source| Error::Io {
                    path: dir.clone(),
                    source,
                })?
                .path();
            if path.is_dir() {
                stack.push(path);
            } else {
                files.push(path);
            }
        }
    }
    files.sort();
    Ok(files)
}

fn read_fixture(path: &Path) -> Result<Fixture, Error> {
    let text = std::fs::read_to_string(path).map_err(|source| Error::Io {
        path: path.to_path_buf(),
        source,
    })?;
    serde_json::from_str(&text).map_err(|source| Error::Parse {
        path: path.to_path_buf(),
        source,
    })
}

/// `path`, relative to `root`, with `/` separators on every platform.
fn slash_relative(path: &Path, root: &Path) -> String {
    let rel = path.strip_prefix(root).unwrap_or(path);
    rel.components()
        .map(|component| component.as_os_str().to_string_lossy())
        .collect::<Vec<_>>()
        .join("/")
}

/// The sets' issues-endpoint list fixtures (`GET /repos/{o}/{r}/issues`, not `/issues/{n}`), in path order.
fn sources(fixtures: &Path) -> Result<Vec<Source>, Error> {
    let mut sets: Vec<String> = std::fs::read_dir(fixtures)
        .map_err(|source| Error::Io {
            path: fixtures.to_path_buf(),
            source,
        })?
        .filter_map(Result::ok)
        .filter(|entry| entry.path().is_dir())
        .map(|entry| entry.file_name().to_string_lossy().into_owned())
        .filter(|set| !HAND_WRITTEN.contains(&set.as_str()))
        .collect();
    sets.sort();
    let mut found = Vec::new();
    for set in sets {
        let repos = fixtures.join(&set).join("repos");
        if !repos.is_dir() {
            continue;
        }
        for path in walk(&repos)? {
            // `repos/<owner>/<repo>/issues/<file>`: only an issues list sits directly in `issues/`.
            let rel = slash_relative(&path, &repos);
            let parts: Vec<&str> = rel.split('/').collect();
            let [owner, repo, "issues", file] = parts[..] else {
                continue;
            };
            if !file.starts_with("GET") || !is_json(file) {
                continue;
            }
            let fixture = read_fixture(&path)?;
            let request = &fixture.request;
            if request.method != "GET" || request.path != format!("/repos/{owner}/{repo}/issues") {
                continue;
            }
            let number = (1..=99)
                .find(|n| numbered_file_name(&request.key(), *n) == file)
                .ok_or_else(|| Error::Unsupported {
                    path: path.clone(),
                    message: "the file name isn't its key's canonical name".into(),
                })?;
            found.push(Source {
                set: set.clone(),
                rel: slash_relative(&path, fixtures),
                number,
                owner: owner.to_owned(),
                repo: repo.to_owned(),
                fixture,
            });
        }
    }
    Ok(found)
}

/// The search query's filters, without the page: which sources are pages of the same search.
type SearchId = (String, String, String, String, String);

fn search_id(source: &Source) -> SearchId {
    (
        source.set.clone(),
        source.owner.clone(),
        source.repo.clone(),
        source.query_value("state").unwrap_or("open").to_owned(),
        source.query_value("per_page").unwrap_or("30").to_owned(),
    )
}

/// The mirror of `source`: its request key and its response body, `total_count` being the search's PRs over all its
/// pages.
fn mirror(source: &Source, total_counts: &BTreeMap<SearchId, usize>) -> Result<Fixture, Error> {
    let unsupported = |message: &str| Error::Unsupported {
        path: PathBuf::from(&source.rel),
        message: message.to_owned(),
    };
    let original = &source.fixture;
    if original.response.body_file.is_some() {
        return Err(unsupported("a `body_file` response isn't mirrored"));
    }
    let known = ["state", "page", "per_page", "creator"];
    if let Some(key) = original.request.query.keys().find(|key| !known.contains(&key.as_str())) {
        return Err(unsupported(&format!("the query key `{key}` isn't mirrored")));
    }
    let state = source.query_value("state").unwrap_or("open");
    let page = source.query_value("page").unwrap_or("1");
    let per_page = source.query_value("per_page").unwrap_or("30");
    let search = source.query_value("creator").is_some();
    let (path, query): (String, Query) = if search {
        let q = pull_request_search_q(&source.owner, &source.repo, state);
        (
            "/search/issues".to_owned(),
            query_from_pairs([
                ("q", q.as_str()),
                ("advanced_search", "true"),
                ("sort", "created"),
                ("order", "desc"),
                ("page", page),
                ("per_page", per_page),
            ]),
        )
    } else {
        (
            format!("/repos/{}/{}/pulls", source.owner, source.repo),
            query_from_pairs([
                ("state", state),
                ("sort", "created"),
                ("direction", "desc"),
                ("page", page),
                ("per_page", per_page),
            ]),
        )
    };
    let body = match source.pull_requests() {
        Some(items) if search => Some(json!({
            "total_count": total_counts.get(&search_id(source)).copied().unwrap_or_default(),
            "incomplete_results": false,
            "items": items,
        })),
        Some(items) => Some(Value::Array(items)),
        None => original.response.body.clone(),
    };
    let headers = original
        .response
        .headers
        .iter()
        .filter(|(name, _)| !name.eq_ignore_ascii_case("link"))
        .map(|(name, value)| (name.clone(), value.clone()))
        .collect();
    Ok(Fixture {
        version: original.version,
        request: FixtureRequest {
            method: "GET".to_owned(),
            path,
            query,
            accept: original.request.accept.clone(),
            body: None,
            when: original.request.when.clone(),
        },
        response: Response {
            status: original.response.status,
            headers,
            body,
            body_text: original.response.body_text.clone(),
            body_file: None,
            delay_ms: original.response.delay_ms,
        },
        note: Some(format!("{NOTE_PREFIX}{}", source.rel)),
    })
}

/// Every generated file: its path under [`FIXTURES_DIR`] and its text.
pub fn files(fixtures: &Path) -> Result<Vec<(PathBuf, String)>, Error> {
    let sources = sources(fixtures)?;
    let mut total_counts: BTreeMap<SearchId, usize> = BTreeMap::new();
    for source in sources.iter().filter(|source| source.query_value("creator").is_some()) {
        *total_counts.entry(search_id(source)).or_default() += source.pull_requests().map_or(0, |prs| prs.len());
    }
    let mut files = Vec::new();
    for source in &sources {
        let fixture = mirror(source, &total_counts)?;
        let key: RequestKey = fixture.request.key();
        let path = PathBuf::from(&source.set)
            .join(dir_for(&key))
            .join(numbered_file_name(&key, source.number));
        // A `Fixture` is plain data; serializing it can't fail.
        let text = serde_json::to_string_pretty(&fixture).unwrap_or_default() + "\n";
        files.push((path, text));
    }
    Ok(files)
}

/// The files under `fixtures` this generator wrote, by their note.
pub fn generated(fixtures: &Path) -> Result<Vec<PathBuf>, Error> {
    let mut found = Vec::new();
    for path in walk(fixtures)? {
        let rel = slash_relative(&path, fixtures);
        let in_mirror_dir = rel.contains("/pulls/") || rel.contains("/search/issues/");
        if !in_mirror_dir || !is_json(&rel) {
            continue;
        }
        let Ok(fixture) = read_fixture(&path) else {
            continue;
        };
        if fixture
            .note
            .as_deref()
            .is_some_and(|note| note.starts_with(NOTE_PREFIX))
        {
            found.push(path.strip_prefix(fixtures).unwrap_or(&path).to_path_buf());
        }
    }
    Ok(found)
}

/// Writes every generated file under `repo`, removing the ones written before that the sets no longer need.
pub fn write(repo: &Path) -> Result<usize, Error> {
    let fixtures = repo.join(FIXTURES_DIR);
    let files = files(&fixtures)?;
    for old in generated(&fixtures)? {
        let path = fixtures.join(old);
        std::fs::remove_file(&path).map_err(|source| Error::Io { path, source })?;
    }
    for (rel, text) in &files {
        let path = fixtures.join(rel);
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent).map_err(|source| Error::Io {
                path: parent.to_path_buf(),
                source,
            })?;
        }
        std::fs::write(&path, text).map_err(|source| Error::Io { path, source })?;
    }
    Ok(files.len())
}

pub fn run(repo: &Path) -> ExitCode {
    match write(repo) {
        Ok(count) => {
            println!("wrote {count} fixtures under {}", repo.join(FIXTURES_DIR).display());
            ExitCode::SUCCESS
        }
        Err(error) => {
            eprintln!("xtask pr-list-fixtures: {error}");
            ExitCode::FAILURE
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn fixtures() -> PathBuf {
        crate::parity::cli::repo_root().join(FIXTURES_DIR)
    }

    #[test]
    fn the_committed_fixtures_are_what_the_generator_writes() {
        let dir = fixtures();
        let expected = files(&dir).unwrap();
        for (path, text) in &expected {
            let committed = std::fs::read_to_string(dir.join(path))
                .unwrap_or_else(|e| panic!("{}: {e}; run `cargo xtask pr-list-fixtures`", path.display()));
            assert!(
                committed == *text,
                "{} is stale; run `cargo xtask pr-list-fixtures`",
                path.display()
            );
        }
        let mut committed = generated(&dir).unwrap();
        committed.sort();
        let mut written: Vec<PathBuf> = expected.into_iter().map(|(path, _)| path).collect();
        written.sort();
        assert_eq!(
            committed, written,
            "generated files the generator no longer writes; run `cargo xtask pr-list-fixtures`"
        );
    }

    fn value(fixture: &str) -> Value {
        serde_json::from_str(fixture).unwrap()
    }

    fn generated_file<'a>(files: &'a [(PathBuf, String)], path: &str) -> &'a str {
        let path = PathBuf::from(path);
        &files
            .iter()
            .find(|(rel, _)| *rel == path)
            .unwrap_or_else(|| panic!("{} isn't generated", path.display()))
            .1
    }

    #[test]
    fn a_pulls_page_holds_the_issues_pages_prs_in_order_without_link() {
        let files = files(&fixtures()).unwrap();
        let page = value(generated_file(
            &files,
            "base/repos/gizmo385/gh-lazy/pulls/GET.direction-desc_page-1_per_page-30_sort-created_state-all.json",
        ));
        assert_eq!(page["request"]["path"], "/repos/gizmo385/gh-lazy/pulls");
        assert_eq!(
            page["request"]["query"],
            json!({"direction": "desc", "page": "1", "per_page": "30", "sort": "created", "state": "all"})
        );
        let items = page["response"]["body"].as_array().unwrap();
        assert_eq!(items.len(), 12);
        assert!(items.iter().all(|item| item.get("draft").is_some()));
        assert_eq!(items[0]["number"], 112);
        assert!(page["response"]["headers"].get("Link").is_none());
        assert_eq!(
            page["note"],
            "generated by cargo xtask pr-list-fixtures from base/repos/gizmo385/gh-lazy/issues/GET.page-1_per_page-30_state-all.json"
        );
    }

    #[test]
    fn a_failure_its_when_and_its_delay_are_copied() {
        let files = files(&fixtures()).unwrap();
        let failed = value(generated_file(
            &files,
            "table-caches/repos/parity-bot/cache-fixture/pulls/GET.direction-desc_page-1_per_page-30_sort-created_state-all.2.json",
        ));
        assert_eq!(failed["response"]["status"], 500);
        assert_eq!(failed["response"]["body"], json!({"message": "Server Error"}));
        assert_eq!(
            failed["request"]["when"],
            json!({"after": [{"method": "GET", "path": "/repos/parity-bot/dotfiles/issues"}]})
        );
        let delayed = value(generated_file(
            &files,
            "lists-error/repos/parity-bot/dotfiles/pulls/GET.direction-desc_page-1_per_page-30_sort-created_state-all.json",
        ));
        assert!(delayed["response"]["delay_ms"].as_u64().unwrap() > 0);
    }

    #[test]
    fn a_creator_page_becomes_a_search_page_counting_every_page() {
        let files = files(&fixtures()).unwrap();
        let searches: Vec<Value> = files
            .iter()
            .filter(|(path, _)| path.starts_with("pr-filters/search/issues"))
            .map(|(_, text)| value(text))
            .collect();
        assert_eq!(searches.len(), 3);
        for search in &searches {
            assert_eq!(
                search["request"]["query"]["q"],
                "is:pr repo:parity-bot/browse-fixture author:@me is:open"
            );
            assert_eq!(search["request"]["query"]["advanced_search"], "true");
            assert_eq!(search["request"]["query"]["sort"], "created");
            assert_eq!(search["request"]["query"]["order"], "desc");
            assert_eq!(search["response"]["body"]["total_count"], 20);
            assert_eq!(search["response"]["body"]["incomplete_results"], false);
        }
        let sizes: Vec<usize> = searches
            .iter()
            .map(|search| search["response"]["body"]["items"].as_array().unwrap().len())
            .collect();
        assert_eq!(sizes.iter().sum::<usize>(), 20);
    }

    #[test]
    fn hand_written_sets_are_skipped() {
        let files = files(&fixtures()).unwrap();
        assert!(files.iter().all(|(path, _)| !path.starts_with("pr-list-issues-first")));
    }

    #[test]
    fn the_search_q_matches_the_apps_rule() {
        assert_eq!(pull_request_search_q("o", "r", "all"), "is:pr repo:o/r author:@me");
        assert_eq!(
            pull_request_search_q("o", "r", "open"),
            "is:pr repo:o/r author:@me is:open"
        );
        assert_eq!(
            pull_request_search_q("o", "r", "closed"),
            "is:pr repo:o/r author:@me is:closed"
        );
    }
}
